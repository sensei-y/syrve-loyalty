import { normalizePhone } from './phone';

describe('normalizePhone', () => {
  it.each([
    ['380991234567', '+380991234567'], // так присылает Telegram
    ['+380991234567', '+380991234567'],
    ['+380 99 123 45 67', '+380991234567'],
    ['0991234567', '+380991234567'],
    ['(099) 123-45-67', '+380991234567'],
    ['991234567', '+380991234567'],
    [' +380501112233 ', '+380501112233'],
  ])('%s → %s', (input, expected) => {
    expect(normalizePhone(input)).toBe(expected);
  });

  it.each([
    ['+48123456789'], // Польша
    ['+12025550123'], // США
    ['38099123456'], // не хватает цифры
    ['3809912345678'], // лишняя цифра
    ['+380091234567'], // национальная часть с 0
    ['099123456a'], // буквы
    [''],
  ])('%s → null', (input) => {
    expect(normalizePhone(input)).toBeNull();
  });
});
